// pchase.c - pointer-chase memory latency / memory-level-parallelism benchmark
// ECSE 6320 Project 2: Cache & Memory Performance Profiling
//
// Each "node" sits `stride` bytes apart in one buffer and holds a pointer to the
// next node. Walking the chain makes every load depend on the previous one, so
// time per load = memory latency at that working-set size (k = 1).
// With k > 1 independent chains interleaved, up to k misses are in flight at once
// (memory-level parallelism), which drives the throughput-latency (intensity) sweep.
//
// Build:  gcc -O2 -march=native -Wall -Wextra -o pchase src/pchase.c
// Output: one CSV row per repetition on stdout; metadata/validation on stderr.

#define _GNU_SOURCE
#include <errno.h>
#include <getopt.h>
#include <linux/perf_event.h>
#include <sched.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/ioctl.h>
#include <sys/mman.h>
#include <sys/syscall.h>
#include <time.h>
#include <unistd.h>

#define HUGE_2M (2UL * 1024 * 1024)

// ---------- small helpers ----------
static uint64_t rng_state = 0x9E3779B97F4A7C15ULL;
static inline uint64_t xorshift64(void) {
    uint64_t x = rng_state;
    x ^= x << 13; x ^= x >> 7; x ^= x << 17;
    return rng_state = x;
}

static double now_ns(void) {
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec * 1e9 + (double)ts.tv_nsec;
}

static uint64_t parse_size(const char *s) {
    char *end;
    double v = strtod(s, &end);
    switch (*end) {
        case 'k': case 'K': v *= 1024.0; break;
        case 'm': case 'M': v *= 1024.0 * 1024; break;
        case 'g': case 'G': v *= 1024.0 * 1024 * 1024; break;
        case '\0': break;
        default: fprintf(stderr, "bad size suffix in '%s'\n", s); exit(1);
    }
    return (uint64_t)v;
}

// Reads AnonHugePages for this process: shows whether THP actually backed the buffer.
static long anon_huge_kb(void) {
    FILE *f = fopen("/proc/self/smaps_rollup", "r");
    if (!f) return -1;
    char line[256];
    long kb = -1;
    while (fgets(line, sizeof line, f))
        if (sscanf(line, "AnonHugePages: %ld kB", &kb) == 1) break;
    fclose(f);
    return kb;
}

// ---------- user-space hardware counters via perf_event_open (no root needed at paranoid=2) ----------
// Counted only around the timed loop, so building/validating the chain is excluded.
// 0 = cycles, 1 = L1D read misses, 2 = dTLB read misses. A counter that fails to open reports NaN.
#define NCTR 3
static int ctr_fd[NCTR] = {-1, -1, -1};
static const char *ctr_name[NCTR] = {"cycles", "L1D read misses", "dTLB read misses"};
static void counters_open(void) {
    uint64_t cache_miss = (uint64_t)PERF_COUNT_HW_CACHE_OP_READ << 8 |
                          (uint64_t)PERF_COUNT_HW_CACHE_RESULT_MISS << 16;
    uint32_t type[NCTR] = {PERF_TYPE_HARDWARE, PERF_TYPE_HW_CACHE, PERF_TYPE_HW_CACHE};
    uint64_t config[NCTR] = {PERF_COUNT_HW_CPU_CYCLES, PERF_COUNT_HW_CACHE_L1D | cache_miss,
                             PERF_COUNT_HW_CACHE_DTLB | cache_miss};
    for (int i = 0; i < NCTR; i++) {
        struct perf_event_attr pe;
        memset(&pe, 0, sizeof pe);
        pe.type = type[i];
        pe.size = sizeof pe;
        pe.config = config[i];
        pe.disabled = 1;
        pe.exclude_kernel = 1;
        pe.exclude_hv = 1;
        ctr_fd[i] = (int)syscall(__NR_perf_event_open, &pe, 0, -1, -1, 0);
        if (ctr_fd[i] < 0)
            fprintf(stderr, "# warning: counter '%s' unavailable (%s); reported as NaN\n",
                    ctr_name[i], strerror(errno));
    }
}
static void counters_start(void) {
    for (int i = 0; i < NCTR; i++)
        if (ctr_fd[i] >= 0) { ioctl(ctr_fd[i], PERF_EVENT_IOC_RESET, 0); ioctl(ctr_fd[i], PERF_EVENT_IOC_ENABLE, 0); }
}
static void counters_stop(double *v) {
    for (int i = 0; i < NCTR; i++) {
        v[i] = 0.0 / 0.0;
        if (ctr_fd[i] < 0) continue;
        ioctl(ctr_fd[i], PERF_EVENT_IOC_DISABLE, 0);
        uint64_t c = 0;
        if (read(ctr_fd[i], &c, sizeof c) == sizeof c) v[i] = (double)c;
    }
}

// ---------- chase kernels ----------
// One function per chain count, generated by scripts/gen_kernels.py, with each
// chain pointer in its own local variable so it stays in a register. A version
// using a `void *p[K]` array was checked with objdump: GCC kept the array on the
// stack (and even vectorized it), adding store-to-load forwarding latency to
// every step - which would inflate measured latency, especially for L1.
// Note: x86-64 has ~14 free general registers, so K >= 16 spills some pointers;
// that adds a few cycles per step, negligible against DRAM latency.
#include "chase_kernels.h"

typedef void (*chase_fn)(void **, uint64_t);
static chase_fn pick_kernel(int k) {
    switch (k) {
        case 1: return chase_1;   case 2: return chase_2;   case 4: return chase_4;
        case 6: return chase_6;   case 8: return chase_8;   case 10: return chase_10;
        case 12: return chase_12; case 16: return chase_16; case 20: return chase_20;
        case 24: return chase_24; case 32: return chase_32; case 40: return chase_40;
        case 48: return chase_48; case 64: return chase_64;
        default: return NULL;
    }
}

static void spin_ms(int ms) {  // let the core ramp its clock before timing
    double end = now_ns() + ms * 1e6;
    volatile uint64_t x = 0;
    while (now_ns() < end) x = x + 1;
    (void)x;
}

static void usage(const char *prog) {
    fprintf(stderr,
        "usage: %s -s SIZE [options]\n"
        "  -s SIZE     working-set size, e.g. 32K, 1M, 512M (required)\n"
        "  -S BYTES    stride between nodes (default 64; use 4096 for one node per page)\n"
        "  -p PATTERN  rand | seq (default rand)\n"
        "  -k K        independent chains: 1,2,4,6,8,10,12,16,20,24,32,40,48,64 (default 1)\n"
        "  -P PAGES    thp | 4k | huge  (thp = system default, 4k = MADV_NOHUGEPAGE,\n"
        "              huge = MADV_HUGEPAGE; default huge)\n"
        "  -c CPU      pin to this CPU (default 2; -1 = no pinning)\n"
        "  -r REPS     timed repetitions (default 5)\n"
        "  -n N        loads per repetition (default max(nodes, 10M))\n"
        "  -w MS       busy-spin warm-up before timing, ms (default 200)\n"
        "  -x SEED     RNG seed (default fixed, for reproducibility)\n"
        "  -H          print CSV header line\n", prog);
    exit(1);
}

int main(int argc, char **argv) {
    uint64_t size = 0, stride = 64, n_loads = 0;
    const char *pattern = "rand", *pages = "huge";
    int k = 1, cpu = 2, reps = 5, warm_ms = 200, header = 0, opt;

    while ((opt = getopt(argc, argv, "s:S:p:k:P:c:r:n:w:x:H")) != -1) {
        switch (opt) {
            case 's': size = parse_size(optarg); break;
            case 'S': stride = parse_size(optarg); break;
            case 'p': pattern = optarg; break;
            case 'k': k = atoi(optarg); break;
            case 'P': pages = optarg; break;
            case 'c': cpu = atoi(optarg); break;
            case 'r': reps = atoi(optarg); break;
            case 'n': n_loads = parse_size(optarg); break;
            case 'w': warm_ms = atoi(optarg); break;
            case 'x': rng_state = strtoull(optarg, NULL, 0) | 1; break;
            case 'H': header = 1; break;
            default: usage(argv[0]);
        }
    }
    if (header)
        printf("size_bytes,stride,pattern,chains,pages,cpu,rep,loads,ns_per_load,"
               "cycles_per_load,lat_ns_per_chain,eff_ghz,mb_per_s,l1d_miss_per_load,"
               "dtlb_miss_per_load,anon_huge_kb\n");
    if (size == 0) { if (header) return 0; usage(argv[0]); }

    chase_fn kernel = pick_kernel(k);
    int is_rand = strcmp(pattern, "rand") == 0;
    if (!kernel || (!is_rand && strcmp(pattern, "seq") != 0) || stride < 8 || stride % 8)
        usage(argv[0]);

    uint64_t nodes = size / stride;
    uint64_t seg = nodes / (uint64_t)k;           // nodes per chain
    if (seg < 2 || nodes > 0xFFFFFFFFULL) { fprintf(stderr, "size/stride/k combination invalid\n"); return 1; }
    uint64_t used = seg * (uint64_t)k;

    // ---- pinning ----
    if (cpu >= 0) {
        cpu_set_t set; CPU_ZERO(&set); CPU_SET(cpu, &set);
        if (sched_setaffinity(0, sizeof set, &set) != 0) { perror("sched_setaffinity"); return 1; }
    }

    // ---- allocation: 2 MiB-aligned mmap, page policy set BEFORE first touch ----
    uint64_t len = (size + HUGE_2M - 1) & ~(HUGE_2M - 1);
    char *raw = mmap(NULL, len + HUGE_2M, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (raw == MAP_FAILED) { perror("mmap"); return 1; }
    char *buf = (char *)(((uintptr_t)raw + HUGE_2M - 1) & ~(HUGE_2M - 1));
    if (strcmp(pages, "4k") == 0) {
        if (madvise(buf, len, MADV_NOHUGEPAGE)) perror("madvise(NOHUGEPAGE)");
    } else if (strcmp(pages, "huge") == 0) {
        if (madvise(buf, len, MADV_HUGEPAGE)) perror("madvise(HUGEPAGE)");
    } else if (strcmp(pages, "thp") != 0) usage(argv[0]);
    memset(buf, 0, len);  // first touch: physical pages get allocated here

    // ---- build chains ----
    uint32_t *order = malloc(used * sizeof *order);
    if (!order) { perror("malloc"); return 1; }
    for (uint64_t i = 0; i < used; i++) order[i] = (uint32_t)i;
    if (is_rand)  // Fisher-Yates shuffle: random visiting order over all nodes
        for (uint64_t i = used - 1; i > 0; i--) {
            uint64_t j = xorshift64() % (i + 1);
            uint32_t t = order[i]; order[i] = order[j]; order[j] = t;
        }
    // chain c = order[c*seg .. (c+1)*seg-1], closed into a cycle
    void *heads[64];
    for (int c = 0; c < k; c++) {
        uint64_t b = (uint64_t)c * seg;
        for (uint64_t i = 0; i < seg; i++) {
            char *from = buf + (uint64_t)order[b + i] * stride;
            char *to = buf + (uint64_t)order[b + (i + 1) % seg] * stride;
            *(void **)from = to;
        }
        heads[c] = buf + (uint64_t)order[b] * stride;
    }

    // ---- validation: each chain is one cycle of exactly seg nodes; all nodes covered once ----
    uint8_t *seen = calloc(used, 1);
    if (!seen) { perror("calloc"); return 1; }
    for (int c = 0; c < k; c++) {
        char *p = heads[c];
        for (uint64_t i = 0; i < seg; i++) {
            uint64_t idx = (uint64_t)(p - buf) / stride;
            if (idx >= used || seen[idx]) { fprintf(stderr, "VALIDATION FAILED (chain %d step %lu)\n", c, (unsigned long)i); return 2; }
            seen[idx] = 1;
            p = *(void **)p;
        }
        if (p != heads[c]) { fprintf(stderr, "VALIDATION FAILED: chain %d does not close\n", c); return 2; }
    }
    free(seen); free(order);

    long huge_kb = anon_huge_kb();
    fprintf(stderr, "# size=%lu stride=%lu nodes_used=%lu chains=%d pattern=%s pages=%s cpu=%d "
            "validation=ok AnonHugePages=%ld kB\n", (unsigned long)size, (unsigned long)stride,
            (unsigned long)used, k, pattern, pages, cpu, huge_kb);

    if (n_loads == 0) n_loads = used > 10000000 ? used : 10000000;
    uint64_t steps = n_loads / (uint64_t)k;
    uint64_t loads = steps * (uint64_t)k;

    counters_open();
    spin_ms(warm_ms);
    kernel(heads, seg);  // one full lap: pulls the working set into cache/TLB

    double bytes_per_load = stride < 64 ? (double)stride : 64.0;
    for (int r = 0; r < reps; r++) {
        double ctr[NCTR];
        counters_start();
        double t0 = now_ns();
        kernel(heads, steps);
        double t1 = now_ns();
        counters_stop(ctr);
        double ns = (t1 - t0) / (double)loads;
        double cpl = ctr[0] / (double)loads;   // NaN propagates if the counter is unavailable
        double ghz = ctr[0] / (t1 - t0);
        double mbps = bytes_per_load * (double)loads / ((t1 - t0) * 1e-9) / 1e6;
        // ns_per_load = time / total loads (throughput view);
        // lat_ns_per_chain = ns_per_load * k = latency each individual load saw
        printf("%lu,%lu,%s,%d,%s,%d,%d,%lu,%.4f,%.3f,%.3f,%.3f,%.1f,%.4f,%.4f,%ld\n",
               (unsigned long)size, (unsigned long)stride, pattern, k, pages, cpu, r,
               (unsigned long)loads, ns, cpl, ns * k, ghz, mbps,
               ctr[1] / (double)loads, ctr[2] / (double)loads, huge_kb);
        fflush(stdout);
    }
    // keep the final pointers observable so the compiler cannot drop the chase
    uintptr_t sink = 0;
    for (int c = 0; c < k; c++) sink ^= (uintptr_t)heads[c];
    if (sink == 1) fprintf(stderr, "#\n");
    munmap(raw, len + HUGE_2M);
    return 0;
}
