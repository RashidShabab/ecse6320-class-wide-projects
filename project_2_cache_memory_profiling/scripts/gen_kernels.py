#!/usr/bin/env python3
"""Generates src/chase_kernels.h: one chase function per chain count K, with each
chain pointer in its own named local variable (p0, p1, ...) so GCC keeps them in
registers. An array version gets spilled/vectorized onto the stack, which adds
store-to-load forwarding latency to every step (verified with objdump)."""
KS = [1, 2, 4, 6, 8, 10, 12, 16, 20, 24, 32, 40, 48, 64]
out = ["// AUTO-GENERATED by scripts/gen_kernels.py - do not edit by hand", ""]
for k in KS:
    v = [f"p{i}" for i in range(k)]
    out.append(f"static void chase_{k}(void **h, uint64_t steps) {{")
    out.append("    void " + ", ".join(f"*{p} = h[{i}]" for i, p in enumerate(v)) + ";")
    out.append("    for (uint64_t s = 0; s < steps; s++) {")
    for p in v:
        out.append(f"        {p} = *(void **){p};")
    out.append("    }")
    out.append("    " + " ".join(f"h[{i}] = {p};" for i, p in enumerate(v)))
    out.append("}")
    out.append("")
open("src/chase_kernels.h", "w").write("\n".join(out))
print("wrote src/chase_kernels.h")
